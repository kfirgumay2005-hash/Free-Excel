import esbuild from 'esbuild';
import process from 'process';
import fs from 'node:fs';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

/**
 * main.ts imports Handsontable's CSS and plugin.css, so esbuild emits them as
 * main.css next to main.js. Obsidian only loads styles.css, so move it there
 * after every build (also on each rebuild in watch mode).
 */
const cssToStyles = {
	name: 'css-to-styles',
	setup(build) {
		build.onEnd(() => {
			if (!fs.existsSync('main.css')) return;
			fs.writeFileSync('styles.css', cleanVendorCss(fs.readFileSync('main.css', 'utf8')));
			fs.unlinkSync('main.css');
		});
	},
};

/**
 * Handsontable's CSS trips Obsidian's CSS lint in a few places that can be
 * dropped without changing how the grid looks in Obsidian (Chromium):
 * - legacy cursor fallbacks (move, -moz-grab, -webkit-grab) before the standard value
 * - clip-path on the license badge, which is already a 1px box with hidden overflow
 * - text-indent on the nesting buttons, whose text is already hidden by font-size: 0
 * - column-gap on sortable headers with a header button (column sorting is not used)
 * - every rule with `:has` in its selector: they style the dialog, the multi-select editor,
 *   sortable headers and checked context-menu items, none of which this plugin shows
 * The `!important` rules stay: they override inline styles that Handsontable sets from
 * JavaScript (selection borders, handles), which no selector specificity can do.
 */
const vendorCssFixes = [
	[/(?:cursor:\s*(?:move|-moz-grab(?:bing)?|-webkit-grab(?:bing)?);\s*)+(cursor:\s*grab(?:bing)?)/g, '$1'],
	[/(\.ht-license-badge\s*\{\s*)clip-path:\s*inset\(50%\);\s*/g, '$1'],
	[/text-indent:\s*-100px;\s*/g, ''],
	[/\.handsontable \.relative\.has-sort-indicator\.has-header-button\s*\{\s*column-gap:[^{}]*\}\s*/g, ''],
	[/(?<=^|[{}])[^{}]*:has\([^{}]*\{[^{}]*\}/g, ''],
];

function cleanVendorCss(css) {
	for (const [pattern, replacement] of vendorCssFixes) {
		const cleaned = css.replace(pattern, replacement);
		// A Handsontable update may reword these rules; fail loudly instead of silently skipping.
		if (prod && cleaned === css)
			throw new Error(`css-to-styles: ${pattern} no longer matches; update vendorCssFixes.`);
		css = cleaned;
	}
	return css;
}

/**
 * ExcelJS's browser bundle ships setImmediate polyfills (from JSZip and core-js)
 * whose legacy-IE fallback injects a <script> element. Obsidian always has
 * MutationObserver and MessageChannel, so that branch can never run; turn its
 * feature test into `false` so the minifier drops the dead code.
 */
const dropScriptPolyfill = {
	name: 'drop-script-polyfill',
	setup(build) {
		build.onLoad({ filter: /exceljs[\\/]dist[\\/].*\.js$/ }, (args) => {
			const source = fs.readFileSync(args.path, 'utf8');
			const pattern =
				/(?:"document"\s*in\s*[\w$]+\s*&&\s*|[\w$]+\s*&&\s*)"onreadystatechange"\s*in\s*[\w$.]+\.createElement\("script"\)/g;
			return { contents: source.replace(pattern, 'false'), loader: 'js' };
		});
		// Dead-code removal only happens when minifying, so only check production builds.
		build.onEnd(() => {
			if (!prod || !fs.existsSync('main.js')) return;
			if (/createElement\(["']script["']\)/.test(fs.readFileSync('main.js', 'utf8')))
				throw new Error(
					'drop-script-polyfill: main.js still creates script elements; update the pattern.',
				);
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	platform: 'browser',
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	// Images/fonts referenced from Handsontable's CSS are inlined so styles.css is self-contained.
	loader: {
		'.png': 'dataurl',
		'.svg': 'dataurl',
		'.gif': 'dataurl',
		'.woff': 'dataurl',
		'.woff2': 'dataurl',
		'.ttf': 'dataurl',
	},
	plugins: [cssToStyles, dropScriptPolyfill],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
